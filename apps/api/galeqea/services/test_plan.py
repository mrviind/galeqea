_RISK_ORDER = {"critical": 0, "high": 1, "medium": 2, "low": 3}

#: The set of known golden-path type keys, and a short human label for each. This
#: is the single source of truth for "what type is this test": the report table,
#: the run board bars, the JUnit testsuite names, and the readiness rules all
#: resolve type through :func:`golden_path_type` / :func:`type_label`, so they can
#: never disagree.
TYPE_KEYS: frozenset[str] = frozenset(spec["key"] for spec in _TYPES)
_TYPE_LABEL: dict[str, str] = {
    "functional": "Functional", "forms": "Forms", "links": "Links", "api": "API",
    "a11y": "Accessibility", "perf": "Performance", "visual": "Visual",
    "responsive": "Responsive", "cross_browser": "Cross-browser", "security": "Security",
    "seo": "SEO", "resilience": "Resilience", "data_driven": "Data-driven",
    "exploratory": "Exploratory", "manual": "Manual", "login": "Login",
}
#: Types whose failures block a release verdict outright (a security hole or a
#: serious accessibility barrier is not a "review", it's a "not ready").
CRITICAL_TYPES: frozenset[str] = frozenset({"security", "a11y"})


def type_from_key(key: str) -> str | None:
    """The type token embedded in a golden-path key `{PROJ}-GP-{TYPE}-{NN}`."""
    if "-GP-" not in (key or ""):
        return None
    token = key.split("-GP-", 1)[1].split("-", 1)[0].lower()
    # Keys strip underscores; map the compacted tokens back.
    return {"crossbrowser": "cross_browser", "datadriven": "data_driven"}.get(token, token)


def golden_path_type(case=None, key: str = "") -> str:
    """The one true test type for a case: its ``provenance.type``, else a known
    type in its tags, else the token in its key, else its category. Every surface
    that groups by type must go through here."""
    if case is not None:
        prov = getattr(case, "provenance", None) or {}
        if prov.get("type"):
            return prov["type"]
        for tag in (getattr(case, "tags", None) or []):
            if tag in TYPE_KEYS:
                return tag
        key = key or getattr(case, "key", "") or ""
    from_key = type_from_key(key)
    if from_key:
        return from_key
    if case is not None:
        return getattr(case, "category", None) or "functional"
    return "functional"


def type_label(type_key: str) -> str:
    return _TYPE_LABEL.get(type_key, type_key.replace("_", " ").title())


def _normalize(discovery: dict) -> dict:
    """Canonicalise the discovery so a count function can rely on shapes: `pages`
    and `apis` are lists, `forms` is an int, whether the caller passed a list, an
    int, or nothing. This keeps the count rules simple and crash-proof."""
    def as_list(v):
        if isinstance(v, (list, tuple)):
            return list(v)
        return [None] * max(0, int(v or 0))

    def as_int(v):
        if isinstance(v, (list, tuple)):
            return len(v)
        return max(0, int(v or 0))

    return {
        **discovery,
        "pages": as_list(discovery.get("pages")) or [None],
        "apis": as_list(discovery.get("apis")),
        "forms": as_int(discovery.get("forms")),
    }


def build_typed_plan(discovery: dict, *, version: int = 1, enabled: dict | None = None) -> dict:
    """The full plan: one row per test type, with counts and estimates. `enabled`
    (a {key: bool} override) lets a caller carry toggles across versions. The
    discovery shape is normalised first, so `forms`/`apis` may be a list or a count."""
    d = _normalize(discovery)
    rows = []
    for spec in _TYPES:
        count = int(spec["count"](d))
        if count <= 0 and spec["key"] in {"forms", "api", "data_driven"}:
            continue  # nothing to test of this type on this site
        on = enabled.get(spec["key"], spec["on"]) if enabled else spec["on"]
        rows.append({
            "key": spec["key"], "label": spec["label"], "category": spec["category"],
            "count": count, "risk": spec["risk"], "confidence": spec["confidence"],
            "est_minutes": round(count * spec["min_per"], 1),
            "est_tokens": (count * spec["tokens_per"]) if on else 0,
            "rerun_tokens": 0,
            "enabled": bool(on),
            "why": spec["why"],
        })
    rows.sort(key=lambda r: (not r["enabled"], _RISK_ORDER.get(r["risk"], 9), r["key"]))
    return {
        "version": version,
        "target": discovery.get("base", ""),
        "types": rows,
        "totals": _totals(rows),
    }


def _totals(rows: list[dict]) -> dict:
    active = [r for r in rows if r["enabled"]]
    return {
        "types_enabled": len(active),
        "types_total": len(rows),
        "test_count": sum(r["count"] for r in active),
        "est_minutes": round(sum(r["est_minutes"] for r in active), 1),
        "est_build_tokens": sum(r["est_tokens"] for r in active),
        "rerun_tokens": 0,
    }


def toggle(plan: dict, key: str, on: bool) -> dict:
    """Return a new plan version with one type flipped on/off. Counts are kept from
    the stored plan (no re-crawl); only enablement, build tokens and totals move."""
    rows = []
    for r in plan["types"]:
        active = on if r["key"] == key else r["enabled"]
        rows.append({**r, "enabled": active, "est_tokens": _rate_tokens(r) if active else 0})
    rows.sort(key=lambda r: (not r["enabled"], _RISK_ORDER.get(r["risk"], 9), r["key"]))
    return {"version": plan["version"] + 1, "target": plan["target"],
            "types": rows, "totals": _totals(rows)}


def _rate_tokens(row: dict) -> int:
    spec = next((s for s in _TYPES if s["key"] == row["key"]), None)
    return int(row["count"] * spec["tokens_per"]) if spec else 0


def diff(old: dict, new: dict) -> list[str]:
    """A human diff between two plan versions: what turned on/off or changed."""
    before = {r["key"]: r for r in old.get("types", [])}
    after = {r["key"]: r for r in new.get("types", [])}
    lines = []
    for key, r in after.items():
        was = before.get(key)
        if was is None:
            lines.append(f"+ added {r['label']}")
        elif was["enabled"] != r["enabled"]:
            lines.append(f"{'+ enabled' if r['enabled'] else '- disabled'} {r['label']}")
    for key, r in before.items():
        if key not in after:
            lines.append(f"- removed {r['label']}")
    return lines


def plan_markdown(plan: dict) -> str:
    """The plan as a versioned Markdown artifact."""
    t = plan["totals"]
    lines = [
        f"# Test plan v{plan['version']}: {plan['target']}",
        "",
        f"**{t['types_enabled']} test type(s), {t['test_count']} test(s), "
        f"~{t['est_minutes']} min, ~{t['est_build_tokens']:,} build tokens** "
        "(re-runs cost 0).",
        "",
        "| Type | Tests | Risk | Confidence | Min | Build tokens | On |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for r in plan["types"]:
        lines.append(
            f"| {r['label']} | {r['count']} | {r['risk']} | {r['confidence']} | "
            f"{r['est_minutes']} | {r['est_tokens']:,} | {'✓' if r['enabled'] else '·'} |"
        )
    return "\n".join(lines) + "\n"
