"""The typed test plan: every kind of test, proposed as a reviewable row.

A plan is the review board: for a discovered site it proposes rows across every
test type a QE team cares about (functional, forms, links, API, accessibility,
performance, visual, responsive, cross-browser, security, SEO, resilience,
data-driven, exploratory, manual), each carrying a count, risk, confidence, and
an estimate of run-minutes and *build* tokens (0 when the type is deterministic /
model-free). Rows are toggleable; editing produces a new plan version with a diff.

Everything is derived deterministically from the discovery, so the same site
proposes the same plan. A model, when present, only sharpens wording; it never
invents the numbers.
"""

from __future__ import annotations

